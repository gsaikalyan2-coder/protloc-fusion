r"""Measure the corpus, freeze the length and alphabet policy, and check it.

Three modes, run from the repository root inside ``.venv``:

    python scripts/validate_sequences.py
        Measure and print. Writes nothing.

    python scripts/validate_sequences.py --freeze --length-quantile 0.99 \
        [--reference-context 1022]
        Measure, then write:
          * the manifest's ``policy`` section;
          * ``data/manifests/DATASET_CARD.md``, generated from the manifest and
            the build report;
          * the frozen values in ``configs/data/uniprot_swissprot.yaml``.
        ``--reference-context`` is optional. It is the trunk's context length
        as read from documentation, and the card reports how many records
        exceed it, labelled as unverified until Phase 7 checks it against the pinned encoder.

    python scripts/validate_sequences.py --check-documents
        The subset of --check that needs no data bytes (manifest, committed
        build report, card, config, rule hashes). This is what CI runs.

    python scripts/validate_sequences.py --check
        Exit 1 unless all of these hold:
          * the corpus on disk has the manifest's SHA-256;
          * the recomputed policy equals the recorded one;
          * the data config carries the recorded values;
          * the card is exactly what the manifest generates.

The measurement comes first and the policy is derived from it. The only input
that is a choice is ``--length-quantile``, and it is recorded beside the value
it produced.
"""

import argparse
from pathlib import Path
import re
import sys

from protloc.data.build import REPORT_FILE
from protloc.data.manifest import (
    read_json_object,
    section,
    sha256_file,
    update_section,
)
from protloc.data.rules import load_corpus_rules
from protloc.data.validate import (
    Measurements,
    PolicyError,
    check_policy,
    derive_policy,
    measure,
)
from protloc.domain.types import LabelState

REPO_ROOT = Path(__file__).resolve().parent.parent
MANIFEST = REPO_ROOT / "data" / "manifests" / "dataset_manifest.json"
CARD = REPO_ROOT / "data" / "manifests" / "DATASET_CARD.md"
CORPUS = REPO_ROOT / "data" / "processed" / "corpus.jsonl"
# The committed copy of the build report, so the card can be checked without data.
REPORT = REPO_ROOT / "data" / "manifests" / REPORT_FILE
RULES_DIR = REPO_ROOT / "backend" / "rules"
DATA_CONFIG = REPO_ROOT / "configs" / "data" / "uniprot_swissprot.yaml"

FREEZE_MARK = "# frozen from data/manifests/dataset_manifest.json"


def config_values(manifest: dict[str, object]) -> dict[str, str]:
    """The YAML scalars the data config must carry, rendered as YAML text."""
    snapshot = section(manifest, "snapshot")
    build = section(manifest, "build")
    policy = section(manifest, "policy")
    return {
        "release": f'"{snapshot["release"]}"',
        "max_length": str(policy["max_sequence_length"]),
        "alphabet": str(policy["alphabet"]),
        "accepted_evidence_codes": str(build["accepted_evidence_codes"]),
    }


def render_config(text: str, values: dict[str, str]) -> str:
    """The data config with each frozen key's value replaced, comments kept."""
    for key, value in values.items():
        pattern = re.compile(rf"^(\s+{key}:)[^\n]*$", re.MULTILINE)
        text, count = pattern.subn(rf"\1 {value}  {FREEZE_MARK}", text)
        if count != 1:
            raise PolicyError(f"{DATA_CONFIG.name}: expected one '{key}:' line, found {count}")
    return text


def _table(rows: list[tuple[str, ...]], header: tuple[str, ...]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def _as_dict(obj: object) -> dict[str, object]:
    if not isinstance(obj, dict):
        raise PolicyError("expected a JSON object in the manifest or report")
    return {str(k): v for k, v in obj.items()}


def render_card(manifest: dict[str, object], report: dict[str, object]) -> str:
    """The dataset card, generated entirely from recorded facts."""
    snap = section(manifest, "snapshot")
    build = section(manifest, "build")
    policy = section(manifest, "policy")
    nonstandard = _as_dict(policy["nonstandard_codes"])
    percentiles = _as_dict(policy["length_percentiles"])
    states = _as_dict(report["label_states"])
    classes = _as_dict(report["label_classes"])
    reference = policy.get("reference_context")

    parts = [
        "# Dataset card: ProtLoc Fusion corpus",
        "",
        "> GENERATED by `python scripts/validate_sequences.py --freeze`, from",
        "> `data/manifests/dataset_manifest.json` and `data/processed/build_report.json`.",
        "> Do not edit. `validate_sequences.py --check` fails if this file differs from",
        "> what those two files generate.",
        "",
        "## Source",
        "",
        _table(
            [
                ("Source", str(snap["source"])),
                ("Release", f"`{snap['release']}` of {snap['release_date']}"),
                ("Downloaded (UTC)", str(snap["downloaded_at_utc"])),
                ("Licence", f"{snap['license']} ({snap['license_url']})"),
                ("Re-download", str(snap["redownload_from"])),
                ("Scope", "Reviewed entries only (Phase 3 decision D1)"),
            ],
            ("Field", "Value"),
        ),
        "",
        "Attribution: UniProt Consortium, UniProtKB/Swiss-Prot. Cite the UniProt paper "
        "for the release year.",
        "",
        "## Corpus",
        "",
        _table(
            [
                ("File", f"`{build['corpus_file']}`"),
                ("SHA-256", f"`{build['corpus_sha256']}`"),
                ("Bytes", str(build["corpus_bytes"])),
                ("Entries read", str(build["entries_read"])),
                ("Records", str(build["record_count"])),
                ("Fragments", str(report["fragment_count"])),
                ("Distinct sequences", str(report["distinct_sequences"])),
                (
                    "Sequences shared by >1 accession",
                    str(report["sequences_shared_by_several_accessions"]),
                ),
                ("Command", "`python scripts/build_dataset.py`"),
            ],
            ("Field", "Value"),
        ),
        "",
        "Excluded entries, by reason (ADR-0006 §3.6, `backend/rules/residue_policy.yaml`):",
        "",
        _table(
            [(k, str(v)) for k, v in _as_dict(build["excluded"]).items()] or [("none", "0")],
            ("Reason", "Entries"),
        ),
        "",
        "Records per organism group:",
        "",
        _table(
            [(k, str(v)) for k, v in _as_dict(report["organism_groups"]).items()],
            ("Group", "Records"),
        ),
        "",
        "## Length policy",
        "",
        f"`MAX_SEQUENCE_LENGTH = {policy['max_sequence_length']}`. Rule: "
        f"{policy['length_rule']}, at quantile {policy['length_quantile']}. "
        f"{policy['records_over_max_length']} records are longer. They stay in the "
        "corpus, so the corpus hash does not depend on this policy, and Phase 4 "
        "excludes them from the splits.",
        "",
        _table(
            [("min", str(policy["length_min"]))]
            + [(f"p{float(p) * 100:g}", str(v)) for p, v in percentiles.items()]
            + [("max", str(policy["length_max"]))],
            ("Statistic", "Residues"),
        ),
        "",
    ]
    if isinstance(reference, dict):
        parts += [
            f"Trunk context reference: {reference['length']} residues, from "
            f"{reference['source']}. **UNVERIFIED. Phase 7 checks it against the pinned encoder.** "
            f"{reference['records_over']} records exceed it.",
            "",
        ]
    parts += [
        f"Command: `{policy['command']}`",
        "",
        "## Residue alphabet",
        "",
        f"Frozen alphabet (observed, after exclusions): `{policy['alphabet']}`. "
        f"Rule: {policy['alphabet_rule']}.",
        "",
        "Normalisation is uppercase plus whitespace removal. No code is substituted.",
        "",
        _table(
            [
                (
                    code,
                    str(_as_dict(v)["residues"]),
                    str(_as_dict(v)["records"]),
                    str(_as_dict(v)["action"]),
                )
                for code, v in nonstandard.items()
            ],
            ("Code", "Residues in corpus", "Records containing", "Action"),
        ),
        "",
        "`keep`: U (selenocysteine) and O (pyrrolysine) are real encoded residues. "
        "X, B and Z are ambiguity codes that the ESM-2 vocabulary tokenises, which "
        "was read from the ESM documentation and is verified in Phase 7. "
        "`exclude_record`: J has no ESM-2 token under the same caveat. A record "
        "containing it is dropped and counted above. A character outside the policy "
        "file stops the build.",
        "",
        "## Labels",
        "",
        "States per task (ADR-0006 §3.1). `unknown` is never `negative`.",
        "",
        _table(
            [
                (task, *(str(_as_dict(counts)[state.value]) for state in LabelState))
                for task, counts in states.items()
            ],
            ("Task", *(state.value for state in LabelState)),
        ),
        "",
        f"Classes per task (GO function: {report['go_function_distinct_terms']} distinct terms):",
        "",
    ]
    for task, counts in classes.items():
        rows = [(k, str(v)) for k, v in _as_dict(counts).items()]
        parts += [
            f"**{task}**",
            "",
            _table(rows or [("none", "0")], ("Class", "Records")),
            "",
        ]
    unmapped = _as_dict(report["unmapped_location_terms"])
    notes = _as_dict(report["unmapped_transit_notes"])
    parts += [
        "Evidence: every code is kept, per label (`accepted_evidence_codes: "
        f"{build['accepted_evidence_codes']}`). Any filter is applied at loss time in "
        "Phase 8.",
        "",
        "## Vocabulary the rules did not map",
        "",
        f"{len(unmapped)} distinct location terms "
        f"({sum(int(str(v)) for v in unmapped.values())} occurrences) and "
        f"{len(notes)} distinct transit-peptide notes were dropped. The full lists "
        "are in `build_report.json`. The ten most frequent terms:",
        "",
        _table(
            [
                (k, str(v))
                for k, v in sorted(unmapped.items(), key=lambda kv: (-int(str(kv[1])), kv[0]))[:10]
            ]
            or [("none", "0")],
            ("Term", "Occurrences"),
        ),
        "",
        "## Inputs that determine the corpus hash",
        "",
        _table(
            [(f"`{k}`", f"`{v}`") for k, v in _as_dict(build["rules_sha256"]).items()]
            + [("parser", f"biopython {_as_dict(build['parser'])['biopython']}")],
            ("Input", "SHA-256 / version"),
        ),
        "",
    ]
    return "\n".join(parts)


def _print(measurements: Measurements) -> None:
    sys.stdout.write(f"records {measurements.record_count}\n")
    sys.stdout.write(
        f"length min {measurements.lengths[0]}  max {measurements.lengths[-1]}  "
        f"p50 {measurements.percentile(0.5)}  p99 {measurements.percentile(0.99)}\n"
    )
    sys.stdout.write("residues " + " ".join(f"{c}:{n}" for c, n in measurements.residue_counts))
    sys.stdout.write("\n")


def _freeze(args: argparse.Namespace, measurements: Measurements) -> int:
    rules = load_corpus_rules(RULES_DIR)
    manifest = read_json_object(MANIFEST)
    build = section(manifest, "build")
    digest, _ = sha256_file(CORPUS)
    if digest != build.get("corpus_sha256"):
        sys.stderr.write("corpus on disk does not match the manifest; rebuild first\n")
        return 1
    policy = derive_policy(measurements, args.length_quantile, rules.residues)
    if args.reference_context is not None:
        policy["reference_context"] = {
            "length": args.reference_context,
            "source": "the ESM-2 documentation",
            "records_over": sum(1 for n in measurements.lengths if n > args.reference_context),
        }
    command = (
        f"python scripts/validate_sequences.py --freeze --length-quantile {args.length_quantile}"
    )
    if args.reference_context is not None:
        command += f" --reference-context {args.reference_context}"
    policy["command"] = command
    manifest = update_section(MANIFEST, "policy", policy)
    CARD.write_bytes(render_card(manifest, read_json_object(REPORT)).encode("utf-8"))
    config_text = DATA_CONFIG.read_text(encoding="utf-8")
    DATA_CONFIG.write_bytes(render_config(config_text, config_values(manifest)).encode("utf-8"))
    sys.stdout.write(
        f"frozen: MAX_SEQUENCE_LENGTH={policy['max_sequence_length']} "
        f"alphabet={policy['alphabet']}\n"
    )
    return 0


def _document_problems() -> list[str]:
    """Checks that need only committed files: manifest, report, card, config, rules."""
    rules = load_corpus_rules(RULES_DIR)
    manifest = read_json_object(MANIFEST)
    problems: list[str] = []
    build = section(manifest, "build")
    section(manifest, "policy")
    report_sha, _ = sha256_file(REPORT)
    if report_sha != build.get("report_sha256"):
        problems.append("data/manifests/build_report.json does not match build.report_sha256")
    if build.get("rules_sha256") != dict(rules.sha256):
        problems.append("backend/rules/ changed since the corpus was built")
    config_text = DATA_CONFIG.read_text(encoding="utf-8")
    if render_config(config_text, config_values(manifest)) != config_text:
        problems.append(f"{DATA_CONFIG.name} does not carry the manifest's frozen values")
    expected_card = render_card(manifest, read_json_object(REPORT)).encode("utf-8")
    if not CARD.is_file() or CARD.read_bytes() != expected_card:
        problems.append("DATASET_CARD.md is not what the manifest generates")
    return problems


def _report(problems: list[str], passed: str) -> int:
    for problem in problems:
        sys.stderr.write(f"FAIL {problem}\n")
    if problems:
        return 1
    sys.stdout.write(passed + "\n")
    return 0


def _check(measurements: Measurements) -> int:
    rules = load_corpus_rules(RULES_DIR)
    manifest = read_json_object(MANIFEST)
    build = section(manifest, "build")
    problems = _document_problems()
    digest, size = sha256_file(CORPUS)
    if digest != build.get("corpus_sha256") or size != build.get("corpus_bytes"):
        problems.append("corpus.jsonl does not match build.corpus_sha256 / corpus_bytes")
    problems += check_policy(measurements, section(manifest, "policy"), rules.residues)
    return _report(problems, "policy check passed: corpus, manifest, config and card agree")


def main() -> int:
    """Dispatch on mode."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--freeze", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument(
        "--check-documents",
        action="store_true",
        help="CI mode: check manifest, report, card and config without the corpus",
    )
    parser.add_argument("--length-quantile", type=float)
    parser.add_argument("--reference-context", type=int)
    args = parser.parse_args()
    if args.freeze and args.length_quantile is None:
        parser.error("--freeze requires --length-quantile")

    try:
        if args.check_documents:
            return _report(
                _document_problems(), "document check passed: manifest, report, card, config"
            )
        measurements = measure(CORPUS)
        _print(measurements)
        if args.freeze:
            return _freeze(args, measurements)
        if args.check:
            return _check(measurements)
    except (PolicyError, ValueError, OSError, KeyError) as exc:
        sys.stderr.write(f"validation failed: {exc}\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
